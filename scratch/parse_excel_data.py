def cyr_to_lat(text):
    if not text:
        return ""
    res = []
    i = 0
    while i < len(text):
        ch = text[i]
        if ch in CYR_TO_LAT:
            res.append(CYR_TO_LAT[ch])
        else:
            res.append(ch)
        i += 1
    return "".join(res)

def clean_phone(p):
    if not p:
        return ""
    digits = re.sub(r'[^\d]', '', p)
    if digits.startswith("998") and len(digits) == 12:
        digits = digits[3:]
    if len(digits) == 9:
        return f"+998 {digits[:2]} {digits[2:5]}-{digits[5:7]}-{digits[7:9]}"
    return p.strip()

def clean_date(d):
    if not d:
        return ""
    d = d.replace('/', '.').strip().rstrip('.')
    parts = d.split('.')
    if len(parts) == 3:
        day, month, year = parts[0], parts[1], parts[2]
        if len(year) == 2:
            y_int = int(year)
            full_y = 1900 + y_int if y_int > 30 else 2000 + y_int
            return f"{day.zfill(2)}.{month.zfill(2)}.{full_y}"
        return f"{day.zfill(2)}.{month.zfill(2)}.{year}"
    return d

def clean_year(y):
    if not y:
        return None
    m = re.search(r'\d{4}', str(y))
    if m:
        return int(m.group(0))
    return None

